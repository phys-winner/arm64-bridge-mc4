"""Rebuild four proven native settings code providers from OBB + reviewed AS3.

Uses the already installed FFDec/JDK; never edits an OBB or downloads tools.
Run: python -B work/build_native_graphics_ui.py
"""
from pathlib import Path
import argparse
import hashlib
import io
import struct
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MOVIES = {
    "30871088.sobfs": "abb6f12da8979f4f857e3c605d5eed8a92138858b07c97b8dbbd2a7df61b6de7",
    "3621326046.sobfs": "73790397d7288147926d6b851457b8eb91cc45d33b98418d8117fffce84da30d",
    "770510667.sobfs": "1557f1d14d1e435ec16ba0535fb0ff183f5af8d973513bf3268f7c6d93876862",
    "766578501.sobfs": "11116b4624f14a277a0bac6b91927de0d30664298dff6732168a4a21458d3c1e",
}
SCRIPT = "scriptsMC4.singleplayer.settings.MenuAdvanced"


def original_movie(name="30871088.sobfs"):
    obb = ROOT / "original/obb/patch.12222.com.gameloft.android.ANMP.GloftM4HM.obb"
    with zipfile.ZipFile(obb) as archive:
        data4 = archive.read("data_4")
    with zipfile.ZipFile(io.BytesIO(data4)) as archive:
        result = archive.read(name)
    if hashlib.sha256(result).hexdigest() != MOVIES[name]:
        raise ValueError("Native settings movie source SHA-256 mismatch")
    return result


def movie_tags(data):
    if data[:4] != b"FWS\x0a" or struct.unpack_from("<I", data, 4)[0] != len(data):
        raise ValueError("Expected complete uncompressed version10 SWF")
    bits = data[8] >> 3
    cursor = 8 + (5 + 4 * bits + 7) // 8 + 4
    result = []
    while cursor + 2 <= len(data):
        start = cursor
        record, = struct.unpack_from("<H", data, cursor)
        cursor += 2
        code, size = record >> 6, record & 63
        if size == 63:
            size, = struct.unpack_from("<I", data, cursor)
            cursor += 4
        end = cursor + size
        if end > len(data):
            raise ValueError("SWF tag exceeds movie")
        result.append((code, data[start:end]))
        cursor = end
        if code == 0:
            break
    if cursor != len(data) or not result or result[-1][0] != 0:
        raise ValueError("SWF lacks exact terminating End tag")
    return result


def verify_overlay(original, overlay):
    before, after = movie_tags(original), movie_tags(overlay)
    if len(before) != len(after) or [c for c, _ in before] != [c for c, _ in after]:
        raise ValueError("UI overlay changed SWF tag structure")
    changed = [i for i, (a, b) in enumerate(zip(before, after)) if a != b]
    if len(changed) != 1 or before[changed[0]][0] != 82:
        raise ValueError("Only the original DoABC tag may change")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--java", type=Path, default=Path("C:/Portable/jdk-24.0.1/bin/java.exe"))
    parser.add_argument("--ffdec", type=Path, default=Path("C:/Portable/Total.Commander/Utilites/FreeFlashDecompile/ffdec-cli.jar"))
    parser.add_argument("--output-dir", type=Path, default=ROOT / "app/assets/native_ui")
    parser.add_argument("--metadata", type=Path, default=ROOT / "arm64_bridge/src/mc4_graphics_ui_asset.h")
    args = parser.parse_args()
    if not args.java.is_file() or not args.ffdec.is_file():
        parser.error("Use the locally installed JDK/FFDec paths; no tool download is performed")
    rows = []
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, source_sha in MOVIES.items():
        original = original_movie(name)
        with tempfile.TemporaryDirectory(prefix="mc4-native-graphics-") as directory:
            directory = Path(directory)
            input_path, output_path = directory / "original.swf", directory / "graphics.swf"
            input_path.write_bytes(original)
            subprocess.run([str(args.java), "-jar", str(args.ffdec), "-replace",
                            str(input_path), str(output_path), SCRIPT,
                            str(ROOT / "arm64_bridge/ui/MenuAdvanced.as")], check=True)
            overlay = output_path.read_bytes()
        verify_overlay(original, overlay)
        target = args.output_dir / name
        target.write_bytes(overlay)
        digest = hashlib.sha256(overlay).hexdigest()
        rows.append(f'    {{"{name}", {len(original)}, 0x{zipfile.crc32(original):08x}u, '
                    f'"{source_sha}", {len(overlay)}, 0x{zipfile.crc32(overlay):08x}u, "{digest}"}},\n')
        print(f"{target}: {len(overlay)} bytes, SHA-256 {digest}")
    args.metadata.parent.mkdir(parents=True, exist_ok=True)
    args.metadata.write_text(
        "// Generated by work/build_native_graphics_ui.py; original OBB stays immutable.\n"
        "#pragma once\n\nnamespace mc4 {\n"
        "struct GraphicsUiMovie {\n"
        "    const char* name; unsigned original_size, original_crc; const char* original_sha;\n"
        "    unsigned size, crc; const char* sha;\n};\n"
        f'constexpr const char* kGraphicsUiAs3Sha = "{hashlib.sha256((ROOT / "arm64_bridge/ui/MenuAdvanced.as").read_bytes()).hexdigest()}";\n'
        "constexpr GraphicsUiMovie kGraphicsUiMovies[] = {\n" + "".join(rows) + "};\n"
        "}  // namespace mc4\n", encoding="utf-8")


if __name__ == "__main__":
    main()
